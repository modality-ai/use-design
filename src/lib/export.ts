import {
  walkTokens,
  resolveToken,
  MODE_EXT,
  type ThemeConfig,
  type ColorValue,
} from "./schema";
import { generateThemeBlock, generateColorModeOverrides, colorToCss } from "./generate";

/**
 * Export resolved theme tokens for consumers that cannot read CSS custom
 * properties: three.js materials, canvas renderers, workers, build scripts.
 *
 * Unlike `generateThemeBlock`, this resolves aliases to concrete values and
 * exposes light/dark pairs as data instead of emitting CSS. `css` mode simply
 * reuses the existing generators so there is one CSS implementation.
 */

export type ExportFormat = "json" | "ts" | "css";
export type ExportMode = "light" | "dark";

export type ResolvedToken = {
  path: string[];
  type?: string;
  /** Light value (or the only value) — DTCG raw value. */
  value: unknown;
  /** Dark counterpart from `use-design.mode`, when defined. */
  dark?: unknown;
  description?: string;
};

function isObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

function isDimension(v: unknown): v is { value: number; unit: string } {
  return isObject(v) && typeof v.value === "number" && typeof v.unit === "string";
}

/** Every token with aliases resolved; throws on a broken or cyclic alias. */
export function resolveTokens(config: ThemeConfig): ResolvedToken[] {
  const root = config.root;
  return walkTokens(root).map((entry) => {
    const resolved = resolveToken(root, entry);
    if (!resolved) throw new Error(`Unresolvable alias at ${entry.path.join(".")}`);

    const mode = (entry.token.$extensions?.[MODE_EXT] ??
      resolved.token.$extensions?.[MODE_EXT]) as { dark?: unknown } | undefined;

    return {
      path: entry.path,
      type: entry.type ?? resolved.type,
      value: resolved.token.$value,
      dark: mode?.dark,
      description: entry.token.$description ?? resolved.token.$description,
    };
  });
}

/** Plain JS value for a token: CSS-ish strings for colors and dimensions. */
function toPlainValue(type: string | undefined, value: unknown): unknown {
  switch (type) {
    case "color":
      return colorToCss(value as ColorValue);
    case "dimension":
      return isDimension(value) ? `${value.value}${value.unit}` : value;
    case "fontFamily":
      return Array.isArray(value) ? value.join(", ") : String(value);
    case "typography": {
      if (!isObject(value)) return value;
      const out: Record<string, unknown> = {};
      for (const [key, child] of Object.entries(value)) {
        out[key] = isDimension(child) ? `${child.value}${child.unit}` : child;
      }
      return out;
    }
    default:
      return value;
  }
}

function selectValue(token: ResolvedToken, mode?: ExportMode): unknown {
  if (mode === "dark" && token.dark !== undefined) return toPlainValue(token.type, token.dark);
  return toPlainValue(token.type, token.value);
}

/** Nested object keyed by token path — `tokens.color.paper`. */
export function toTokenObject(
  tokens: ResolvedToken[],
  mode?: ExportMode
): Record<string, unknown> {
  const root: Record<string, unknown> = {};

  for (const token of tokens) {
    let node = root;
    for (const segment of token.path.slice(0, -1)) {
      if (!isObject(node[segment])) node[segment] = {};
      node = node[segment] as Record<string, unknown>;
    }

    const key = token.path[token.path.length - 1]!;
    const light = selectValue(token, mode);
    node[key] =
      mode === undefined && token.dark !== undefined
        ? { light, dark: toPlainValue(token.type, token.dark) }
        : light;
  }

  return root;
}

export function toJson(config: ThemeConfig, mode?: ExportMode): string {
  const tokens = resolveTokens(config).map((token) => ({
    path: token.path.join("."),
    type: token.type,
    value: selectValue(token, mode),
    ...(mode === undefined && token.dark !== undefined
      ? { dark: toPlainValue(token.type, token.dark) }
      : {}),
    ...(token.description ? { description: token.description } : {}),
  }));

  return `${JSON.stringify(
    { theme: config.name, version: config.version ?? null, tokens },
    null,
    2
  )}\n`;
}

export function toTypeScript(config: ThemeConfig, mode?: ExportMode): string {
  const body = JSON.stringify(toTokenObject(resolveTokens(config), mode), null, 2);
  return [
    "// Generated by use-design — do not edit.",
    `// Theme: ${config.name}${config.version ? ` (${config.version})` : ""}`,
    "",
    `export const tokens = ${body} as const;`,
    "",
    "export type Tokens = typeof tokens;",
    "",
  ].join("\n");
}

/** Reuses the build-time CSS generators, so `tokens --format css` cannot drift. */
export function toCss(config: ThemeConfig, mode?: ExportMode): string {
  const parts = [generateThemeBlock(config)];
  if (mode !== "dark") {
    const overrides = generateColorModeOverrides(config);
    if (overrides) parts.push("", overrides);
  }
  return `${parts.join("\n")}\n`;
}

export function exportTheme(
  config: ThemeConfig,
  format: ExportFormat,
  mode?: ExportMode
): string {
  switch (format) {
    case "json":
      return toJson(config, mode);
    case "ts":
      return toTypeScript(config, mode);
    case "css":
      return toCss(config, mode);
  }
}
